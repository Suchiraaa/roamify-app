/**
 * Component to render appropriate category icon for any stop
 */
export function CategoryIcon({ category, className = "", size = 18 }) {
  const norm = (category || "").toLowerCase();
  if (norm.includes("food") || norm.includes("culinary") || norm.includes("restaurant")) {
    return <UtensilsIcon className={className} size={size} />;
  }
  if (norm.includes("culture") || norm.includes("museum") || norm.includes("historic") || norm.includes("heritage")) {
    return <LandmarkIcon className={className} size={size} />;
  }
  if (norm.includes("adventure") || norm.includes("sport") || norm.includes("hike") || norm.includes("climb")) {
    return <MountainIcon className={className} size={size} />;
  }
  if (norm.includes("worship") || norm.includes("temple") || norm.includes("church") || norm.includes("shrine") || norm.includes("mosque")) {
    return <ChurchIcon className={className} size={size} />;
  }
  // Default to nature / scenic vista
  return <TreePineIcon className={className} size={size} />;
}


